/// Icons for wardens that have no art of their own in the clients, shared
/// with the website. The RAM warden is the brand ram the clients already
/// draw. 8-bit sprites, generated by `scripts/warden-sprites.py`.
fn icon(id: &str) -> Option<&'static str> {
    match id {
        "wazuh" => Some(include_str!("../../../web/assets/wardens/wazuh.svg")),
        _ => None,
    }
}

/// What the Wazuh warden last saw.
#[derive(Clone, Debug, Default, Serialize)]
pub struct WazuhReport {
    pub agent_name: String,
    pub local: LocalAgent,
    pub manager: Option<ManagerAgent>,
    pub alerts: Vec<Alert>,
    /// Why part of the picture is missing: no manager configured, wrong
    /// password, manager down. Shown to the user as-is.
    pub problems: Vec<String>,
}

impl WazuhReport {
    /// Whether the agent can report, from both its own state and the
    /// manager's. Either one saying "connected" is enough; the manager saying
    /// anything but `active` outranks an unreadable local state.
    fn health(&self) -> AgentHealth {
        let manager_active = self.manager.as_ref().map(|m| m.status == "active");
        if !self.local.installed && self.manager.is_none() {
            return AgentHealth::Missing;
        }
        if self.local.is_connected() || manager_active == Some(true) {
            return AgentHealth::Connected;
        }
        if manager_active == Some(false) || self.local.status.is_some() {
            return AgentHealth::Disconnected;
        }
        AgentHealth::Unknown
    }
}

/// The add-on wardens' state, shared by the poller and the routes.
pub struct Wardens {
    entitlement_path: PathBuf,
    wazuh_cfg: config::Wazuh,
    wazuh: RwLock<(Status, Option<WazuhReport>)>,
}

static GLOBAL: OnceLock<Arc<Wardens>> = OnceLock::new();

impl Wardens {
    pub fn new(cfg: &Config) -> Wardens {
        Wardens {
            entitlement_path: cfg.db_path.with_file_name("entitlement.json"),
            wazuh_cfg: cfg.wardens.wazuh.clone(),
            wazuh: RwLock::new((Status::off("Not checked yet", "", 0), None)),
        }
    }

    /// The installed instance, or one made from `cfg` the first time it is
    /// asked for (tests, and a daemon that has not started the pollers).
    pub fn global(cfg: &Config) -> Arc<Wardens> {
        GLOBAL.get_or_init(|| Arc::new(Wardens::new(cfg))).clone()
    }

    /// Re-read on every use, so a purchase or an expiry takes effect at once.
    pub fn entitlement(&self) -> Entitlement {
        Entitlement::load(&self.entitlement_path)
    }

    fn unlocked(&self, w: &WardenInfo) -> bool {
        self.entitlement().allows(w, wardens::now())
    }

    /// One warden's current status.
    fn status(&self, st: &AppState, w: &WardenInfo) -> Status {
        if !self.unlocked(w) {
            return Status::locked(w);
        }
        match w.id {
            "ram" => {
                let m = st.memory();
                let rung = ladder::rung_for(&st.cfg.ladder, &st.pressure(), ladder::available_bytes(st.platform.memory.as_ref()));
                let used = if m.total > 0 { m.used() as f64 * 100.0 / m.total as f64 } else { 0.0 };
                wardens::ram_status(rung, used, wardens::now())
            }
            "wazuh" if !self.wazuh_cfg.enabled => Status::off(
                "Turned off",
                "Set [wardens.wazuh] enabled = true and point it at your Wazuh manager.",
                0,
            ),
            "wazuh" => self.wazuh.read().unwrap().0.clone(),
            _ => Status::off("Unknown warden", "", 0),
        }
    }

    fn enabled(&self, w: &WardenInfo) -> bool {
        match w.id {
            "wazuh" => self.wazuh_cfg.enabled,
            _ => true,
        }
    }

    fn entry(&self, st: &AppState, w: &WardenInfo) -> Value {
        json!({
            "id": w.id,
            "name": w.name,
            "role": w.role,
            "access": w.access,
            "icon": icon(w.id).map(|_| format!("/wardens/{}/icon.svg", w.id)),
            "unlocked": self.unlocked(w),
            "enabled": self.enabled(w),
            "status": self.status(st, w),
        })
    }

    /// One poll of the Wazuh warden. Does nothing unless unlocked and enabled.
    pub async fn poll_wazuh(&self, client: Option<&Client>) {
        if !self.wazuh_cfg.enabled || !self.unlocked(&wardens::WAZUH) {
            return;
        }
        let c = &self.wazuh_cfg;
        let mut report = WazuhReport {
            agent_name: if c.agent_name.trim().is_empty() {
                ramwarden_wazuh::default_agent_name()
            } else {
                c.agent_name.trim().to_string()
            },
            local: LocalAgent::read(),
            ..Default::default()
        };
        let mut levels = Vec::new();
        match client {
            None => report.problems.push("No Wazuh manager configured; showing this computer's agent only.".into()),
            Some(client) => {
                if client.has_manager() {
                    match client.agent(&report.agent_name).await {
                        Ok(Some(a)) => report.manager = Some(a),
                        Ok(None) => report.problems.push(format!(
                            "The manager has no agent named \"{}\". Set [wardens.wazuh] agent_name if it enrolled under another name.",
                            report.agent_name
                        )),
                        Err(e) => report.problems.push(e.to_string()),
                    }
                }
                if client.has_indexer() {
                    match client.alerts(&report.agent_name, c.min_level, c.lookback_hours).await {
                        Ok(a) => {
                            levels = a.iter().map(|x| x.level).collect();
                            report.alerts = a;
                        }
                        Err(e) => report.problems.push(e.to_string()),
                    }
                } else {
                    report.problems.push("No indexer configured, so alerts are not shown.".into());
                }
            }
        }
        let t = ThreatThresholds { min_level: c.min_level, alert_level: c.alert_level };
        let mut status = wardens::assess_threats(report.health(), &levels, t, wardens::now());
        // "Clear" must not hide that part of the picture is missing.
        if status.level == Level::Clear && !report.problems.is_empty() {
            let why = report.problems.join(" ");
            if report.manager.is_none() && !report.local.is_connected() {
                status = Status::off("Cannot reach Wazuh", why, status.checked_at);
            } else {
                status.detail = format!("{} {why}", status.detail);
            }
        }
        *self.wazuh.write().unwrap() = (status, Some(report));
    }

    /// Build the client and poll forever. A configuration error is reported
    /// as the warden's status, once, and the poller stops.
    pub fn spawn(self: Arc<Self>, handle: &tokio::runtime::Handle) {
        if !self.wazuh_cfg.enabled {
            return;
        }
        handle.spawn(async move {
            let client = match wazuh_client(&self.wazuh_cfg) {
                Ok(c) => c,
                Err(e) => {
                    tracing::warn!("wazuh warden off: {e}");
                    *self.wazuh.write().unwrap() = (Status::off("Wazuh settings need fixing", e, wardens::now()), None);
                    return;
                }
            };
            let every = Duration::from_secs(self.wazuh_cfg.poll_seconds.max(30));
            tracing::info!("wazuh warden: polling every {}s", every.as_secs());
            loop {
                self.poll_wazuh(client.as_ref()).await;
                tokio::time::sleep(every).await;
            }
        });
    }
}

/// `Ok(None)` when neither manager nor indexer is configured.
fn wazuh_client(c: &config::Wazuh) -> Result<Option<Client>, String> {
    if c.manager_url.trim().is_empty() && c.indexer_url.trim().is_empty() {
        return Ok(None);
    }
    let ca_pem = match &c.ca_file {
        Some(p) => Some(std::fs::read(p).map_err(|e| format!("cannot read ca_file {}: {e}", p.display()))?),
        None => None,
    };
    Client::new(Endpoints {
        manager_url: c.manager_url.clone(),
        api_user: c.api_user.clone(),
        api_password: Secret::new(c.api_password.clone()),
        indexer_url: c.indexer_url.clone(),
        indexer_user: c.indexer_user.clone(),
        indexer_password: Secret::new(c.indexer_password.clone()),
        ca_pem,
        timeout: Duration::from_secs(c.timeout_seconds),
    })
    .map(Some)
    .map_err(|e| e.to_string())
}

// ── Routes ──────────────────────────────────────────────────────────────────

pub async fn list(State(st): State<AppState>) -> Json<Value> {
    let w = Wardens::global(&st.cfg);
    let ent = w.entitlement();
    Json(json!({
        "paid": ent.paid_at(wardens::now()),
        "wardens": wardens::CATALOGUE.iter().map(|x| w.entry(&st, x)).collect::<Vec<_>>(),
    }))
}

pub async fn one(State(st): State<AppState>, Path(id): Path<String>) -> impl IntoResponse {
    let Some(info) = wardens::find(&id) else {
        return (StatusCode::NOT_FOUND, Json(json!({"error": format!("no warden called {id}")})));
    };
    let w = Wardens::global(&st.cfg);
    let mut entry = w.entry(&st, info);
    let report = match info.id {
        "wazuh" if w.unlocked(info) => json!(w.wazuh.read().unwrap().1),
        _ => Value::Null,
    };
    entry["report"] = report;
    (StatusCode::OK, Json(entry))
}

pub async fn icon_svg(Path(id): Path<String>) -> impl IntoResponse {
    match icon(&id) {
        Some(svg) => (StatusCode::OK, [(header::CONTENT_TYPE, "image/svg+xml")], svg).into_response(),
        None => StatusCode::NOT_FOUND.into_response(),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn report(installed: bool, local: Option<&str>, manager: Option<&str>) -> WazuhReport {
        WazuhReport {
            local: LocalAgent { installed, status: local.map(str::to_string), last_keepalive: None },
            manager: manager.map(|s| ManagerAgent {
                id: "001".into(),
                name: "desk".into(),
                status: s.into(),
                version: None,
                last_keep_alive: None,
            }),
            ..Default::default()
        }
    }

    #[test]
    fn health_combines_the_local_and_manager_views() {
        assert_eq!(report(false, None, None).health(), AgentHealth::Missing);
        assert_eq!(report(true, None, None).health(), AgentHealth::Unknown);
        assert_eq!(report(true, Some("connected"), None).health(), AgentHealth::Connected);
        assert_eq!(report(true, None, Some("active")).health(), AgentHealth::Connected);
        assert_eq!(report(true, None, Some("disconnected")).health(), AgentHealth::Disconnected);
        assert_eq!(report(true, Some("pending"), None).health(), AgentHealth::Disconnected);
        // Installed elsewhere (a remote agent we only see through the manager).
        assert_eq!(report(false, None, Some("never_connected")).health(), AgentHealth::Disconnected);
    }

    #[test]
    fn every_add_on_warden_has_an_icon() {
        for w in wardens::CATALOGUE.iter().filter(|w| w.access != wardens::Access::Free) {
            let svg = icon(w.id).unwrap_or_else(|| panic!("{} has no icon", w.id));
            assert!(svg.trim_start().starts_with("<svg"), "{}", w.id);
        }
    }

    #[test]
    fn a_misconfigured_manager_url_is_reported_not_fatal() {
        let c = config::Wazuh { manager_url: "http://wazuh.lan:55000".into(), ..Default::default() };
        let e = wazuh_client(&c).err().unwrap();
        assert!(e.contains("https"), "{e}");
        assert!(wazuh_client(&config::Wazuh::default()).unwrap().is_none());
    }
}
