//! The wardens, as the daemon runs and serves them.
//!
//! `ramwarden_core::wardens` says which wardens exist and what is unlocked;
//! this module polls the add-on wardens in the background and serves
//! `/wardens`, `/wardens/{id}` and `/wardens/{id}/icon.svg`. The RAM warden
//! needs no poller: its status is read from the ladder on each request.
//!
//! A locked or disabled warden does no work at all: the Wazuh poller checks
//! the plan before every poll, so it never contacts a manager or reads the
//! agent's files for a user who has not unlocked it. See `docs/specs/wardens.md`.

