//! The wardens, as the daemon runs and serves them.
//!
//! `ramwarden_core::wardens` says which wardens exist and what is unlocked;
//! this module polls the add-on wardens in the background and serves
//! `/wardens`, `/wardens/{id}`, `/wardens/{id}/icon.svg` and
//! `/wardens/{id}/setup`. The RAM warden needs no poller: its status is read
//! from the ladder on each request.
//!
//! A locked or disabled warden does no work at all: the ThreatWarden poller checks
//! the plan before every poll, so it never contacts anything or reads the
//! agent's files for a user who has not unlocked it. See `docs/specs/wardens.md`.

pub mod threat;

use std::path::PathBuf;
use std::sync::{Arc, OnceLock};

use axum::Json;
use axum::extract::{Path, State};
use axum::http::{StatusCode, header};
use axum::response::IntoResponse;
use ramwarden_core::config::Config;
use ramwarden_core::ladder;
use ramwarden_core::wardens::{self, Entitlement, Status, WardenInfo};
use serde_json::{Value, json};

use crate::hub::AppState;
use threat::ThreatWarden;

/// Icons for wardens that have no art of their own in the clients, shared
/// with the website. The RAM warden is the brand ram the clients already
/// draw. 8-bit sprites, generated by `scripts/warden-sprites.py`.
fn icon(id: &str) -> Option<&'static str> {
    match id {
        "threat" => Some(include_str!("../../../../web/assets/wardens/threat.svg")),
        _ => None,
    }
}

/// The add-on wardens' state, shared by the pollers and the routes.
pub struct Wardens {
    entitlement_path: PathBuf,
    /// The key entitlement records must be signed with: the compiled-in one,
    /// except in tests.
    public_key: Option<String>,
    pub threat: Arc<ThreatWarden>,
}

static GLOBAL: OnceLock<Arc<Wardens>> = OnceLock::new();

impl Wardens {
    pub fn new(cfg: &Config) -> Wardens {
        Wardens::with_public_key(cfg, wardens::PUBLIC_KEY.map(str::to_string))
    }

    /// For tests, which sign their own records. Production uses [`Wardens::new`].
    pub fn with_public_key(cfg: &Config, public_key: Option<String>) -> Wardens {
        Wardens {
            public_key,
            entitlement_path: cfg.db_path.with_file_name("entitlement.json"),
            threat: Arc::new(ThreatWarden::new(cfg)),
        }
    }

    /// The installed instance, or one made from `cfg` the first time it is
    /// asked for (tests, and a daemon that has not started the pollers).
    pub fn global(cfg: &Config) -> Arc<Wardens> {
        GLOBAL.get_or_init(|| Arc::new(Wardens::new(cfg))).clone()
    }

    /// Install `w` as the daemon's wardens. Only the first install counts.
    pub fn install(w: Wardens) -> Arc<Wardens> {
        let _ = GLOBAL.set(Arc::new(w));
        GLOBAL.get().unwrap().clone()
    }

    /// Re-read on every use, so a purchase or an expiry takes effect at once.
    pub fn entitlement(&self) -> Entitlement {
        Entitlement::load_verified(&self.entitlement_path, self.public_key.as_deref())
    }

    pub fn unlocked(&self, w: &WardenInfo) -> bool {
        self.entitlement().allows(w, wardens::now())
    }

    /// One warden's current status.
    fn status(&self, st: &AppState, w: &WardenInfo) -> Status {
        if !self.unlocked(w) {
            return Status::locked(w);
        }
        match w.id {
            "ram" => {
                let m = st.memory();
                let rung = ladder::rung_for(&st.cfg.ladder, &st.pressure(), ladder::available_bytes(st.platform.memory.as_ref()));
                let used = if m.total > 0 { m.used() as f64 * 100.0 / m.total as f64 } else { 0.0 };
                wardens::ram_status(rung, used, wardens::now())
            }
            "threat" => self.threat.status(),
            _ => Status::off("Unknown warden", "", 0),
        }
    }

    fn enabled(&self, w: &WardenInfo) -> bool {
        match w.id {
            "threat" => self.threat.enabled(),
            _ => true,
        }
    }

    fn entry(&self, st: &AppState, w: &WardenInfo) -> Value {
        json!({
            "id": w.id,
            "name": w.name,
            "role": w.role,
            "access": w.access,
            "price": w.price,
            "upgrade_url": w.upgrade_url,
            "icon": icon(w.id).map(|_| format!("/wardens/{}/icon.svg", w.id)),
            "unlocked": self.unlocked(w),
            "enabled": self.enabled(w),
            "status": self.status(st, w),
        })
    }

    /// Start every add-on warden's poller.
    pub fn spawn(self: &Arc<Self>, handle: &tokio::runtime::Handle) {
        let me = self.clone();
        self.threat.clone().spawn(handle, move || me.unlocked(&wardens::THREAT));
    }
}

// ── Routes ──────────────────────────────────────────────────────────────────

pub async fn list(State(st): State<AppState>) -> Json<Value> {
    let w = Wardens::global(&st.cfg);
    let ent = w.entitlement();
    Json(json!({
        "paid": ent.paid_at(wardens::now()),
        "tier": ent.tier,
        "plan_status": ent.status,
        "pet": ent.shows_pet(wardens::now()),
        "wardens": wardens::CATALOGUE.iter().map(|x| w.entry(&st, x)).collect::<Vec<_>>(),
    }))
}

pub async fn one(State(st): State<AppState>, Path(id): Path<String>) -> impl IntoResponse {
    let Some(info) = wardens::find(&id) else {
        return (StatusCode::NOT_FOUND, Json(json!({"error": format!("no warden called {id}")})));
    };
    let w = Wardens::global(&st.cfg);
    let mut entry = w.entry(&st, info);
    let report = match info.id {
        "threat" if w.unlocked(info) => json!(w.threat.report()),
        _ => Value::Null,
    };
    entry["report"] = report;
    (StatusCode::OK, Json(entry))
}

/// "Turn on": install and enrol what the warden needs. Started only by the
/// user, because it raises the OS's admin prompt.
pub async fn setup(State(st): State<AppState>, Path(id): Path<String>) -> impl IntoResponse {
    let Some(info) = wardens::find(&id) else {
        return (StatusCode::NOT_FOUND, Json(json!({"error": format!("no warden called {id}")})));
    };
    let w = Wardens::global(&st.cfg);
    if !w.unlocked(info) {
        return (StatusCode::FORBIDDEN, Json(json!({"error": Status::locked(info).headline})));
    }
    match info.id {
        "threat" => match w.threat.start_setup(&tokio::runtime::Handle::current()) {
            Ok(()) => (StatusCode::ACCEPTED, Json(json!({"started": true}))),
            Err(why) => (StatusCode::CONFLICT, Json(json!({"started": false, "error": why}))),
        },
        _ => (StatusCode::BAD_REQUEST, Json(json!({"error": format!("{} needs no setup", info.name)}))),
    }
}

pub async fn icon_svg(Path(id): Path<String>) -> impl IntoResponse {
    match icon(&id) {
        Some(svg) => (StatusCode::OK, [(header::CONTENT_TYPE, "image/svg+xml")], svg).into_response(),
        None => StatusCode::NOT_FOUND.into_response(),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_add_on_warden_has_an_icon() {
        for w in wardens::CATALOGUE.iter().filter(|w| w.access != wardens::Access::Free) {
            let svg = icon(w.id).unwrap_or_else(|| panic!("{} has no icon", w.id));
            assert!(svg.trim_start().starts_with("<svg"), "{}", w.id);
        }
    }
}
