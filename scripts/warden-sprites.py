"""Draw the wardens' 8-bit sprites as SVG.

The Wazuh warden is a cyborg ram: the RAM warden's own 48x48 sprite (the
pixel ram in macos/menubar Companion.swift, ported cell for cell) with the
viewer's-left half turned to machine: chrome horn and plates, a cyan scanning
visor, an antenna and a chest core. Same grid, outline and palette as the ram,
so the two read as one team.

    python3 scripts/warden-sprites.py > web/assets/wardens/wazuh.svg
"""
import math, sys
N=48
c=['.']*(N*N)
def put(x,y,k):
    if 0<=x<N and 0<=y<N: c[y*N+x]=k
def get(x,y): return c[y*N+x]
def box(x,y,w,h,k):
    for yy in range(y,y+h):
        for xx in range(x,x+w): put(xx,yy,k)
def ellipse(cx,cy,rx,ry,wool):
    for y in range(N):
        for x in range(N):
            dx,dy=x-cx,y-cy
            if dx*dx/(rx*rx)+dy*dy/(ry*ry)>1: continue
            edge=dx*dx/((rx-1.2)**2)+dy*dy/((ry-1.2)**2)>1
            put(x,y,'o' if edge else ('s' if dx>rx*0.45 or dy>ry*0.55 else 'b' if dx<-rx*0.35 and dy<0 else 'w') if wool else 'k')
# --- the RAM warden's sprite (macos/menubar Companion.swift PixelRam) ---
box(17,42,5,6,'o'); box(27,42,5,6,'o'); box(18,43,3,4,'k'); box(28,43,3,4,'k')
ellipse(24,38,9,7,True)
box(18,34,2,3,'b'); box(29,35,2,3,'s')
for center in (8.0,40.0):
    for y in range(10,33):
        for x in range(N):
            dx,dy=x-center,y-21
            r=math.hypot(dx,dy)
            if not (3.7<=r<=9.4): continue
            inward = dx>1 if center<24 else dx<-1
            if inward and dy>3: continue
            put(x,y,'o' if r>8.2 or r<4.8 else 'H' if dy<-2 else 'j' if dy>3 else 'h')
    x=int(center); box(x-1,20,3,2,'h'); box(x,21,2,4,'H')
ellipse(11,23,5,4,True); ellipse(37,23,5,4,True)
for y in range(12,37):
    half = 8+(y-12) if y<17 else 12 if y<23 else max(4,12-(y-22)*2//3)
    for x in range(24-half,24+half+1):
        edge = x==24-half or x==24+half or y==12 or y==36
        put(x,y,'o' if edge else 's' if x>27 or y>29 else 'b' if x<19 else 'w')
box(21,10,3,2,'o'); box(24,9,2,3,'o'); box(22,11,5,3,'b')
for x in (15,26):
    box(x-1,19,9,6,'o'); box(x,20,7,4,'e'); box(x+1,23,5,1,'E'); box(x+1,21,5,1,'o')
box(22,27,5,3,'b'); box(20,31,9,2,'o'); box(21,33,7,1,'o'); put(21,31,'s'); put(27,31,'s')
box(23,35,3,1,'o'); box(22,37,5,2,'o'); box(23,37,3,3,'s'); put(24,40,'o')
# --- cyborg: the left half (viewer's left) is machine ---
metal={'w':'m','b':'M','s':'d','h':'m','H':'M','j':'d','k':'d'}
for y in range(N):
    for x in range(0,24):
        k=get(x,y)
        if k in metal: put(x,y,metal[k])
# plate seam down the middle of the face, with rivets
for y in range(13,36):
    if get(24,y) not in '.o': put(24,y,'o')
for (x,y) in ((19,15),(19,28),(14,32),(21,34),(9,26),(13,24)): 
    if get(x,y) not in '.o': put(x,y,'r' if (x,y)==(9,26) else 'M')
# a panel line across the cheek
for x in range(14,24):
    if get(x,26) not in '.o': put(x,26,'d')
# visor over the left eye: one bar, scanning cyan
box(13,19,11,6,'o'); box(14,20,9,4,'v'); box(15,21,4,1,'V'); box(20,22,2,1,'V')
# right eye glows red (organic but awakened)
box(26,20,7,4,'e'); box(27,21,5,1,'o'); box(28,21,2,1,'r')
box(27,23,5,1,'E')
# antenna from the metal crown
for y in range(3,12): put(17,y,'d')
put(16,4,'d'); put(18,4,'d')
box(16,1,3,2,'r'); put(17,0,'o'); put(15,1,'o'); put(19,1,'o'); put(15,2,'o'); put(19,2,'o'); box(16,3,3,1,'o'); put(17,1,'R')
# mechanical hoof/leg on the left
box(18,43,3,4,'d'); box(18,44,3,1,'M')
# chest core light where the wool meets the plate
box(22,39,3,3,'o'); put(23,40,'v')
pal={'o':'#0d0b0e','m':'#9aa3ad','M':'#e3e8ee','d':'#5b636d','w':'#f24455','s':'#a8232f','b':'#ff7a86',
     'h':'#c4303d','H':'#f29ca6','j':'#7a1822','k':'#2a1418','v':'#38e8ff','V':'#d6fdff','e':'#ffffff','E':'#cfd6dd',
     'r':'#ff2b3a','R':'#ffd2d6'}
rects=[]
for y in range(N):
    x=0
    while x<N:
        k=c[y*N+x]
        if k=='.': x+=1; continue
        x2=x
        while x2<N and c[y*N+x2]==k: x2+=1
        rects.append(f'<rect x="{x}" y="{y}" width="{x2-x}" height="1" fill="{pal[k]}"/>'); x=x2
out=[f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {N} {N}" width="96" height="96" shape-rendering="crispEdges" role="img" aria-label="Wazuh Warden">',
 '  <title>Wazuh Warden</title>',
 '  <!-- 8-bit cyborg ram on the RAM warden\'s 48x48 sprite. Generated by scripts/warden-sprites.py. -->']
out+=['  '+r for r in rects]; out.append('</svg>')
print('\n'.join(out))
if '--map' in sys.argv:
    for y in range(N): print(''.join(c[y*N:(y+1)*N]),file=sys.stderr)
