#!/usr/bin/env node
// Keep the site's lettering on a two-CSS-pixel grid at its 80 x 56 header size.
// The mascot comes from the canonical vector sprite; no fonts are downloaded.
import { readFileSync, writeFileSync } from 'node:fs';

const assets = new URL('../web/assets/', import.meta.url);
const mascot = readFileSync(new URL('pets/ram.svg', assets), 'utf8').match(/<rect\b[^>]*\/>/g);
if (!mascot?.length) throw new Error('The canonical RAM sprite has no pixel rectangles.');

const glyphs = {
  W: ['10001', '10001', '10001', '10101', '10101', '11011', '10001'],
  A: ['01110', '10001', '10001', '11111', '10001', '10001', '10001'],
  R: ['11110', '10001', '10001', '11110', '10100', '10010', '10001'],
  D: ['11110', '10001', '10001', '10001', '10001', '10001', '11110'],
  E: ['11111', '10000', '10000', '11110', '10000', '10000', '11111'],
  N: ['10001', '11001', '11001', '10101', '10011', '10011', '10001'],
};
const letters = [...'WARDEN'].map((letter, i) => {
  const pixels = glyphs[letter].flatMap((row, y) => [...row].flatMap((on, x) =>
    on === '1' ? [`M${i * 6 + x} ${y}h1v1h-1z`] : []));
  return `    <path d="${pixels.join('')}"/>`;
});

writeFileSync(new URL('warden-wordmark.svg', assets), `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 80 56" width="80" height="56" shape-rendering="crispEdges" role="img" aria-label="WARDEN">
  <title>WARDEN</title>
  <!-- Generated by scripts/build-site-wordmark.mjs. -->
  <g transform="translate(16 -5)">
    ${mascot.join('\n    ')}
  </g>
  <g transform="translate(5 40) scale(2)" fill="#fff2f7">
${letters.join('\n')}
  </g>
</svg>
`);
console.log('Built the 80 x 56 pixel WARDEN header wordmark.');
