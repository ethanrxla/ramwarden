#!/usr/bin/env bash
# Install only this app's bundled payload; never sources or distributes .env.
set -euo pipefail
PAYLOAD="$(cd "$(dirname "$0")/payload" && pwd)"
BASE="$HOME"
TEST=0
if [ "${1:-}" = '--test-root' ]; then
  BASE="${2:?temporary root required}"
  case "$BASE" in /tmp/*|/private/tmp/*|/var/folders/*) ;; *) echo 'Test root must be temporary.'; exit 2 ;; esac
  TEST=1
fi
if [ "${1:-}" = '--verify' ]; then
  for ITEM in ramwarden-daemon ramwarden-usage-sync config.toml RamWarden.app extension; do test -e "$PAYLOAD/$ITEM"; done
  echo 'Bundled installation payload verified.'
  exit 0
fi
[ "$(id -u)" -ne 0 ] || { echo 'Open the installer as your normal Mac user, not root.'; exit 1; }
BIN_DIR="$BASE/.local/bin"
CONFIG_DIR="$BASE/.config/ramwarden"
AGENTS="$BASE/Library/LaunchAgents"
SUPPORT="$BASE/Library/Application Support/RamWarden"
BACKUP="$SUPPORT/Backups/$(date +%Y%m%d-%H%M%S)-$$"
mkdir -p "$BIN_DIR" "$CONFIG_DIR" "$AGENTS" "$SUPPORT" "$BASE/Applications" "$BASE/Library/Logs" "$BACKUP"
for ITEM in ramwarden-daemon ramwarden-usage-sync; do
  test -x "$PAYLOAD/$ITEM"
  [ ! -f "$BIN_DIR/$ITEM" ] || cp -p "$BIN_DIR/$ITEM" "$BACKUP/$ITEM"
  install -m 755 "$PAYLOAD/$ITEM" "$BIN_DIR/.$ITEM.new"
done
[ -f "$CONFIG_DIR/config.toml" ] || install -m 600 "$PAYLOAD/config.toml" "$CONFIG_DIR/config.toml"
# Stage the app and extension before stopping any running component.
STAGE="$(mktemp -d "$BASE/Applications/.warden-install.XXXXXX")"
trap 'rm -rf "$STAGE"' EXIT
ditto "$PAYLOAD/RamWarden.app" "$STAGE/RamWarden.app"
ditto "$PAYLOAD/extension" "$STAGE/extension"
DOMAIN="gui/$(id -u)"
if [ "$TEST" -eq 0 ]; then
for LABEL in com.ramwarden.usage com.ramwarden.menubar com.ramwarden.daemon; do
  launchctl bootout "$DOMAIN/$LABEL" 2>/dev/null || true
  for _ in $(seq 1 50); do launchctl print "$DOMAIN/$LABEL" >/dev/null 2>&1 || break; sleep .2; done
done
fi
[ ! -d "$BASE/Applications/RamWarden.app" ] || mv "$BASE/Applications/RamWarden.app" "$BACKUP/RamWarden.app"
mv "$STAGE/RamWarden.app" "$BASE/Applications/RamWarden.app"
[ ! -d "$SUPPORT/extension" ] || mv "$SUPPORT/extension" "$BACKUP/extension"
mv "$STAGE/extension" "$SUPPORT/extension"
for ITEM in ramwarden-daemon ramwarden-usage-sync; do mv -f "$BIN_DIR/.$ITEM.new" "$BIN_DIR/$ITEM"; done
# launchd definitions are generated by the native launcher with proper plist escaping.
if [ "$TEST" -eq 0 ]; then
for LABEL in com.ramwarden.daemon com.ramwarden.menubar com.ramwarden.usage; do
  test -f "$AGENTS/$LABEL.plist"
  launchctl bootstrap "$DOMAIN" "$AGENTS/$LABEL.plist"
done
fi
echo 'Installed. Your settings, secrets, account tokens, history, and pet colors were preserved.'
echo 'Enable the bundled browser extension in each browser profile you use.'
